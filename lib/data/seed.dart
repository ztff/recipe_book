/// 空库时灌示例数据；返回是否执行了灌入。
Future<bool> ensureSeed(AppDb db) async {
  if (db.allRecipes().isNotEmpty) return false;
  for (final d in seedDrafts()) {
    db.saveRecipe(d, searchKey(d.name));
  }
  return true;
}

Future<void> reseed(AppDb db) async {
  db.wipeAll();
  for (final d in seedDrafts()) {
    db.saveRecipe(d, searchKey(d.name));
  }
}
