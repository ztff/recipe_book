/// 命中词表的总字数，用来在两次识别结果里挑更像中文的那个。
int vocabScore(String text) {
  var score = 0;
  final cleaned = text.replaceAll(RegExp(r'[^\u4e00-\u9fa5]'), '');
  for (var i = 0; i < cleaned.length; i++) {
    for (var len = 2; len <= 4; len++) {
      if (i + len > cleaned.length) break;
      final w = cleaned.substring(i, i + len);
      if (kAllWords.contains(w)) {
        score += len;
        break;
      }
    }
  }
  return score;
}

/// 保守纠错：只改「换成形近正字后命中词表」的两字片段。
String fixTypos(String text) {
  if (text.isEmpty) return text;
  final chars = text.split('');
  for (var i = 0; i + 1 < chars.length; i++) {
    final pair = chars[i] + chars[i + 1];
    if (!_isChinese(pair)) continue;
    if (kAllWords.contains(pair)) continue;
    for (var slot = 0; slot < 2; slot++) {
      final wrong = chars[i + slot];
      final right = kCharFix[wrong];
      if (right == null) continue;
      final candidate = slot == 0 ? right + chars[i + 1] : chars[i] + right;
      if (kAllWords.contains(candidate)) {
        chars[i + slot] = right;
        break;
      }
    }
  }
  return chars.join();
}

bool _isChinese(String s) =>
    RegExp(r'^[\u4e00-\u9fa5]{2}$').hasMatch(s);
